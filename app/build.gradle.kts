// Include AppFunctions metadata generated by KSP in the APK.
androidComponents {
    onVariants { variant ->
        val generatedAssets = layout.buildDirectory
            .dir("generated/ksp/${variant.name}/resources/assets")

        generatedAssets.get().asFile.mkdirs()

        variant.sources.assets?.addStaticSourceDirectory(
            generatedAssets.get().asFile.absolutePath
        )
    }
}

// Generate metadata before merging assets.
tasks.matching {
    it.name.startsWith("merge") && it.name.endsWith("Assets")
}.configureEach {
    val variantName = name
        .removePrefix("merge")
        .removeSuffix("Assets")

    dependsOn(
        tasks.matching {
            it.name == "ksp${variantName}Kotlin"
        }
    )
}

